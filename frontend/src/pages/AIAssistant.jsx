import { useState, useEffect, useRef } from 'react';
import {
  Bot, Send, Loader2, AlertTriangle, CheckCircle, Lightbulb,
  Target, Info, Sparkles, MessageSquare, Shield, TrendingUp,
  ChevronDown, ChevronUp, Zap
} from 'lucide-react';
import { analyzeRequirement, getAiStatus, aiChat } from '../services/api';

// ─── AI Status Badge ───────────────────────────────────────────────
function AIStatusBadge({ status }) {
  if (!status) return null;
  if (status.gemini_available) {
    return (
      <span className="inline-flex items-center gap-1.5 text-xs bg-emerald-100 text-emerald-700 px-2.5 py-1 rounded-full font-medium border border-emerald-200">
        <Sparkles size={11} />
        Google Gemini Active ({status.model})
      </span>
    );
  }
  return (
    <span className="inline-flex items-center gap-1.5 text-xs bg-amber-100 text-amber-700 px-2.5 py-1 rounded-full font-medium border border-amber-200">
      <Zap size={11} />
      Mock Mode — No API Key
    </span>
  );
}

// ─── Mock Notice Banner ───────────────────────────────────────────
function MockBanner({ fallback_reason }) {
  return (
    <div className="bg-amber-50 border border-amber-200 rounded-lg px-4 py-3 text-xs text-amber-800">
      <strong>⚠ Mock Analysis Active</strong>
      {fallback_reason
        ? ` — Gemini fallback triggered: ${fallback_reason}`
        : ' — Add GEMINI_API_KEY to backend/.env for real AI analysis.'
      }
    </div>
  );
}

// ─── Gemini Notice Banner ─────────────────────────────────────────
function GeminiBanner({ model }) {
  return (
    <div className="bg-emerald-50 border border-emerald-200 rounded-lg px-4 py-3 text-xs text-emerald-800 flex items-center gap-2">
      <Sparkles size={13} className="text-emerald-600 flex-shrink-0" />
      <span><strong>Powered by Google Gemini ({model})</strong> — Analysis generated by real AI.</span>
    </div>
  );
}

// ─── List Section Card ────────────────────────────────────────────
function ListCard({ icon: Icon, iconClass, title, items }) {
  if (!items || items.length === 0) return null;
  return (
    <div className="card p-5">
      <div className="flex items-center gap-2 mb-3">
        <Icon size={16} className={iconClass} />
        <h3 className="font-medium text-gray-800 text-sm">{title}</h3>
      </div>
      <ul className="space-y-1.5">
        {items.map((item, i) => (
          <li key={i} className="flex items-start gap-2 text-sm text-gray-600">
            <span className="text-gray-400 mt-0.5 flex-shrink-0">•</span>
            {item}
          </li>
        ))}
      </ul>
    </div>
  );
}

// ─── ANALYSIS TAB ─────────────────────────────────────────────────
function AnalysisTab({ aiStatus }) {
  const [form, setForm] = useState({
    project_name: '', module_name: '', feature_name: '',
    requirement_description: '', user_story: ''
  });
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState(null);
  const [error, setError] = useState(null);

  const handleAnalyze = async (e) => {
    e.preventDefault();
    if (!form.requirement_description.trim()) {
      setError('Requirement description is required');
      return;
    }
    setLoading(true);
    setError(null);
    setResult(null);
    try {
      const data = await analyzeRequirement(form);
      setResult(data);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  const clarityColor = (s) => s >= 8 ? 'text-emerald-600' : s >= 5 ? 'text-amber-600' : 'text-red-600';
  const clarityBarColor = (s) => s >= 8 ? 'bg-emerald-500' : s >= 5 ? 'bg-amber-500' : 'bg-red-500';

  return (
    <div className="space-y-5">
      {/* Input Form */}
      <div className="card p-6">
        <h3 className="font-medium text-gray-800 mb-4">Requirement Analysis Input</h3>
        <form onSubmit={handleAnalyze} className="space-y-4">
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            <div>
              <label className="label">Project Name</label>
              <input className="input-field" placeholder="e.g. Banking App"
                value={form.project_name} onChange={e => setForm(f => ({ ...f, project_name: e.target.value }))} />
            </div>
            <div>
              <label className="label">Module Name</label>
              <input className="input-field" placeholder="e.g. Authentication"
                value={form.module_name} onChange={e => setForm(f => ({ ...f, module_name: e.target.value }))} />
            </div>
            <div>
              <label className="label">Feature Name</label>
              <input className="input-field" placeholder="e.g. User Login"
                value={form.feature_name} onChange={e => setForm(f => ({ ...f, feature_name: e.target.value }))} />
            </div>
          </div>

          <div>
            <label className="label">Requirement Description <span className="text-red-500">*</span></label>
            <textarea
              className={`input-field h-32 resize-y ${error ? 'border-red-400' : ''}`}
              placeholder="Describe the feature, functionality, or workflow in detail. Include inputs, outputs, business rules, and expected behaviors..."
              value={form.requirement_description}
              onChange={e => { setForm(f => ({ ...f, requirement_description: e.target.value })); setError(null); }}
            />
            <div className="flex justify-between mt-1">
              {error ? <p className="text-xs text-red-500">{error}</p> : <span />}
              <span className="text-xs text-gray-400">{form.requirement_description.length} chars</span>
            </div>
          </div>

          <div>
            <label className="label">User Story <span className="text-gray-400 font-normal text-xs ml-1">(optional)</span></label>
            <textarea className="input-field h-16 resize-none"
              placeholder='"As a [role], I want to [action] so that [benefit]"'
              value={form.user_story}
              onChange={e => setForm(f => ({ ...f, user_story: e.target.value }))} />
          </div>

          <button type="submit" disabled={loading} className="btn-primary">
            {loading
              ? <><Loader2 size={16} className="animate-spin" /> Analyzing with {aiStatus?.gemini_available ? 'Gemini AI' : 'Mock Engine'}…</>
              : <><Send size={16} /> Analyze Requirement</>
            }
          </button>
        </form>
      </div>

      {/* Results */}
      {result && (
        <div className="space-y-4 animate-fadeIn">
          {result.mode === 'gemini' ? <GeminiBanner model={result.model} /> : <MockBanner fallback_reason={result.fallback_reason} />}

          {/* Requirement Summary */}
          {result.requirement_summary && (
            <div className="bg-slate-50 border border-slate-200 rounded-xl p-5">
              <p className="text-xs font-semibold text-slate-500 uppercase tracking-wide mb-1">Requirement Summary</p>
              <p className="text-sm text-slate-700">{result.requirement_summary}</p>
            </div>
          )}

          {/* Clarity Score */}
          <div className="card p-5">
            <div className="flex items-center gap-3 mb-3">
              <Target size={18} className="text-blue-600" />
              <h3 className="font-medium text-gray-800">Requirement Clarity Score</h3>
            </div>
            <div className="flex items-end gap-4 mb-3">
              <span className={`text-4xl font-bold ${clarityColor(result.clarity_score)}`}>
                {result.clarity_score}<span className="text-xl text-gray-400">/10</span>
              </span>
              <div className="flex-1 pb-1">
                <div className="h-3 bg-gray-200 rounded-full overflow-hidden">
                  <div
                    className={`h-full rounded-full transition-all duration-500 ${clarityBarColor(result.clarity_score)}`}
                    style={{ width: `${(result.clarity_score / 10) * 100}%` }}
                  />
                </div>
              </div>
            </div>
            <p className="text-sm text-gray-600">{result.clarity_analysis}</p>
          </div>

          {/* Grid: 4 analysis cards */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <ListCard icon={AlertTriangle} iconClass="text-amber-500" title="Identified Gaps" items={result.identified_gaps} />
            <ListCard icon={Info} iconClass="text-red-500" title="Missing Information" items={result.missing_information} />
            <ListCard icon={Info} iconClass="text-orange-500" title="Potential Ambiguities" items={result.ambiguities} />
            <ListCard icon={Shield} iconClass="text-purple-500" title="Potential Risks" items={result.potential_risks} />
          </div>

          {/* Suggestions and Recommendations */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <ListCard icon={Lightbulb} iconClass="text-blue-500" title="Suggested Test Scenarios" items={result.suggested_scenarios} />
            <ListCard icon={CheckCircle} iconClass="text-emerald-500" title="Testing Recommendations" items={result.testing_recommendations} />
          </div>

          {/* Priority Recommendations */}
          {result.priority_recommendations && (
            <div className="card p-5">
              <div className="flex items-center gap-2 mb-2">
                <TrendingUp size={16} className="text-blue-600" />
                <h3 className="font-medium text-gray-800 text-sm">Priority Recommendations</h3>
              </div>
              <p className="text-sm text-gray-600">{result.priority_recommendations}</p>
            </div>
          )}

          {/* Overall Recommendation */}
          {result.overall_recommendation && (
            <div className={`border rounded-xl p-5 ${result.mode === 'gemini' ? 'bg-emerald-50 border-emerald-200' : 'bg-blue-50 border-blue-200'}`}>
              <div className="flex items-center gap-2 mb-2">
                <Bot size={16} className={result.mode === 'gemini' ? 'text-emerald-600' : 'text-blue-600'} />
                <h3 className={`font-medium text-sm ${result.mode === 'gemini' ? 'text-emerald-800' : 'text-blue-800'}`}>Overall Recommendation</h3>
              </div>
              <p className={`text-sm ${result.mode === 'gemini' ? 'text-emerald-700' : 'text-blue-700'}`}>{result.overall_recommendation}</p>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

// ─── CHAT TAB ─────────────────────────────────────────────────────
function ChatTab({ aiStatus }) {
  const [messages, setMessages] = useState([
    { role: 'assistant', content: 'Hello! I\'m your AI QA assistant powered by Google Gemini. I can help you with test case design, requirement analysis, testing strategies, and more. What would you like to know?' }
  ]);
  const [input, setInput] = useState('');
  const [loading, setLoading] = useState(false);
  const bottomRef = useRef(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages]);

  const handleSend = async (e) => {
    e.preventDefault();
    const msg = input.trim();
    if (!msg || loading) return;

    setMessages(m => [...m, { role: 'user', content: msg }]);
    setInput('');
    setLoading(true);

    try {
      const result = await aiChat(msg, {});
      setMessages(m => [...m, { role: 'assistant', content: result.response, model: result.model }]);
    } catch (err) {
      setMessages(m => [...m, {
        role: 'assistant',
        content: `⚠ ${err.message}`,
        isError: true
      }]);
    } finally {
      setLoading(false);
    }
  };

  if (!aiStatus?.gemini_available) {
    return (
      <div className="card p-8 text-center">
        <Bot size={40} className="text-gray-300 mx-auto mb-3" />
        <p className="font-medium text-gray-500">AI Chat Requires Gemini API Key</p>
        <p className="text-sm text-gray-400 mt-1">Add <code className="font-mono bg-gray-100 px-1 rounded text-xs">GEMINI_API_KEY</code> to <code className="font-mono bg-gray-100 px-1 rounded text-xs">backend/.env</code> to enable the AI chat.</p>
      </div>
    );
  }

  return (
    <div className="card flex flex-col" style={{ height: '600px' }}>
      {/* Messages */}
      <div className="flex-1 overflow-y-auto p-4 space-y-4">
        {messages.map((msg, i) => (
          <div key={i} className={`flex gap-3 ${msg.role === 'user' ? 'flex-row-reverse' : ''}`}>
            <div className={`w-8 h-8 rounded-full flex items-center justify-center flex-shrink-0 text-white text-sm font-bold ${msg.role === 'user' ? 'bg-blue-600' : 'bg-gradient-to-br from-purple-600 to-blue-600'}`}>
              {msg.role === 'user' ? 'U' : <Bot size={16} />}
            </div>
            <div className={`max-w-[80%] rounded-2xl px-4 py-3 text-sm ${
              msg.role === 'user'
                ? 'bg-blue-600 text-white rounded-tr-sm'
                : msg.isError
                ? 'bg-red-50 text-red-700 border border-red-200 rounded-tl-sm'
                : 'bg-gray-100 text-gray-800 rounded-tl-sm'
            }`}>
              <p className="whitespace-pre-wrap leading-relaxed">{msg.content}</p>
              {msg.model && (
                <p className="text-xs text-gray-400 mt-1">via {msg.model}</p>
              )}
            </div>
          </div>
        ))}
        {loading && (
          <div className="flex gap-3">
            <div className="w-8 h-8 rounded-full bg-gradient-to-br from-purple-600 to-blue-600 flex items-center justify-center">
              <Bot size={16} className="text-white" />
            </div>
            <div className="bg-gray-100 rounded-2xl rounded-tl-sm px-4 py-3">
              <div className="flex gap-1">
                <div className="w-2 h-2 bg-gray-400 rounded-full animate-bounce" style={{ animationDelay: '0ms' }} />
                <div className="w-2 h-2 bg-gray-400 rounded-full animate-bounce" style={{ animationDelay: '150ms' }} />
                <div className="w-2 h-2 bg-gray-400 rounded-full animate-bounce" style={{ animationDelay: '300ms' }} />
              </div>
            </div>
          </div>
        )}
        <div ref={bottomRef} />
      </div>
      {/* Input */}
      <div className="border-t border-gray-200 p-4">
        <form onSubmit={handleSend} className="flex gap-2">
          <input
            className="input-field flex-1"
            placeholder="Ask about test cases, testing strategies, QA best practices…"
            value={input}
            onChange={e => setInput(e.target.value)}
            disabled={loading}
            maxLength={4000}
          />
          <button type="submit" disabled={loading || !input.trim()} className="btn-primary flex-shrink-0">
            {loading ? <Loader2 size={16} className="animate-spin" /> : <Send size={16} />}
          </button>
        </form>
        <p className="text-xs text-gray-400 mt-1.5 text-center">
          Powered by Google Gemini · {input.length}/4000
        </p>
      </div>
    </div>
  );
}

// ─── MAIN COMPONENT ───────────────────────────────────────────────
export default function AIAssistant() {
  const [aiStatus, setAiStatus] = useState(null);
  const [activeTab, setActiveTab] = useState('analysis');

  useEffect(() => {
    getAiStatus()
      .then(setAiStatus)
      .catch(() => setAiStatus({ gemini_available: false, mode: 'mock', message: 'Could not reach backend' }));
  }, []);

  return (
    <div className="max-w-4xl mx-auto space-y-5">
      {/* Header */}
      <div className="card p-5 flex items-start gap-4">
        <div className="w-12 h-12 bg-gradient-to-br from-blue-600 to-purple-600 rounded-xl flex items-center justify-center flex-shrink-0">
          <Bot size={24} className="text-white" />
        </div>
        <div className="flex-1">
          <div className="flex items-center gap-3 flex-wrap">
            <h2 className="font-semibold text-gray-900">AI Assistant</h2>
            <AIStatusBadge status={aiStatus} />
          </div>
          <p className="text-sm text-gray-500 mt-1">
            Analyze requirements, identify gaps, and chat with AI about testing strategies.
          </p>
          {aiStatus && !aiStatus.gemini_available && (
            <p className="text-xs text-amber-700 mt-1.5 bg-amber-50 border border-amber-200 rounded-lg px-3 py-2">
              💡 Untuk mengaktifkan Google Gemini: salin <code className="font-mono">backend/.env.example</code> ke <code className="font-mono">backend/.env</code>, lalu isi <code className="font-mono">GEMINI_API_KEY</code> dengan API key dari{' '}
              <a href="https://aistudio.google.com/app/apikey" target="_blank" rel="noreferrer" className="underline">aistudio.google.com</a>.
            </p>
          )}
        </div>
      </div>

      {/* Tabs */}
      <div className="flex gap-1 bg-gray-100 p-1 rounded-xl w-fit">
        {[
          { id: 'analysis', label: 'Requirement Analysis', icon: Target },
          { id: 'chat', label: 'AI Chat', icon: MessageSquare },
        ].map(({ id, label, icon: Icon }) => (
          <button
            key={id}
            onClick={() => setActiveTab(id)}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-sm font-medium transition-all ${
              activeTab === id
                ? 'bg-white text-blue-700 shadow-sm'
                : 'text-gray-500 hover:text-gray-700'
            }`}
          >
            <Icon size={15} />
            {label}
          </button>
        ))}
      </div>

      {/* Tab Content */}
      {activeTab === 'analysis' && <AnalysisTab aiStatus={aiStatus} />}
      {activeTab === 'chat' && <ChatTab aiStatus={aiStatus} />}
    </div>
  );
}
